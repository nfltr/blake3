//go:build ignore

// gen_arm64.go writes compress_arm64.s: BLAKE3's compression of 4 chunks
// at once in arm64 NEON, one chunk per 32-bit vector lane, the way the
// official implementation's blake3_neon.c does it (rotations by 12, 8 and 7
// with shift and shift-right-insert; by 16 with a halfword reverse).
//
//	go run gen_arm64.go
package main

import (
	"bytes"
	"fmt"
	"os"
)

var b bytes.Buffer

func p(format string, args ...any) { fmt.Fprintf(&b, "\t"+format+"\n", args...) }

// Registers: V0-V15 the state (V0-V7 also the chaining value between
// blocks), V16-V23 the message words of one step, V24-V27 temporaries,
// V28-V30 IV[0..2] (R19 IV[3]), V31 the byte shuffle that rotates
// each word right by 8.
func v(i int) string { return fmt.Sprintf("V%d", i) }

// g4 runs G on four columns (or diagonals) at once, interleaved.
func g4(cols [4][4]int) {
	add := func(src, dst int) { p("VADD %s.S4, %s.S4, %s.S4", v(src), v(dst), v(dst)) }
	xor := func(src, dst, out int) { p("VEOR %s.B16, %s.B16, %s.B16", v(src), v(dst), v(out)) }
	rot := func(n int) {
		for i, c := range cols {
			a, bb, cc, d := c[0], c[1], c[2], c[3]
			t := 24 + i
			switch n {
			case 16:
				xor(a, d, d)
				p("VREV32 %s.H8, %s.H8", v(d), v(d))
			case 12, 7:
				xor(cc, bb, t)
				p("VSHL $%d, %s.S4, %s.S4", 32-n, v(t), v(bb))
				p("VSRI $%d, %s.S4, %s.S4", n, v(t), v(bb))
			case 8:
				xor(a, d, d)
				p("VTBL V31.B16, [%s.B16], %s.B16", v(d), v(d))
			}
		}
	}
	for half := 0; half < 2; half++ {
		for i, c := range cols {
			add(c[1], c[0])
			add(16+2*i+half, c[0])
		}
		if half == 0 {
			rot(16)
		} else {
			rot(8)
		}
		for _, c := range cols {
			add(c[3], c[2])
		}
		if half == 0 {
			rot(12)
		} else {
			rot(7)
		}
	}
}

func loadMsg(sched [16]int, from int) {
	for i := 0; i < 8; i++ {
		p("FMOVQ %d(R10), F%d", 16*sched[from+i], 16+i)
	}
}

// transpose4 makes d[j] = lane j of s[0..3] (a 4x4 transpose of words),
// using V24-V27.
func transpose4(s, d [4]int) {
	p("VTRN1 %s.S4, %s.S4, V24.S4", v(s[1]), v(s[0]))
	p("VTRN2 %s.S4, %s.S4, V25.S4", v(s[1]), v(s[0]))
	p("VTRN1 %s.S4, %s.S4, V26.S4", v(s[3]), v(s[2]))
	p("VTRN2 %s.S4, %s.S4, V27.S4", v(s[3]), v(s[2]))
	p("VTRN1 V26.D2, V24.D2, %s.D2", v(d[0]))
	p("VTRN1 V27.D2, V25.D2, %s.D2", v(d[1]))
	p("VTRN2 V26.D2, V24.D2, %s.D2", v(d[2]))
	p("VTRN2 V27.D2, V25.D2, %s.D2", v(d[3]))
}

func main() {
	fmt.Fprint(&b, "// Code generated by gen_arm64.go. DO NOT EDIT.\n\n//go:build arm64 && !purego\n\n#include \"textflag.h\"\n")
	fn("compressChunksNEON", "4 * ChunkSize", 16, ChunkSize)
	fn("compressBlocksNEON", "4 * BlockSize", 1, BlockSize)
	if err := os.WriteFile("compress_arm64.s", b.Bytes(), 0o644); err != nil {
		panic(err)
	}
}

const (
	BlockSize = 64
	ChunkSize = 1024
)

// fn writes a function compressing 4 inputs of buf, stride bytes apart,
// one per lane, each blocks blocks long, into their chaining values.
func fn(name, size string, blocks, stride int) {
	fmt.Fprintf(&b, "\n// func %s(cvs *[4][8]uint32, buf *[%s]byte, key *[8]uint32, ctr *[8]uint32, flags *[16]uint32, msg *[64]uint32)\n", name, size)
	fmt.Fprintf(&b, "TEXT ·%s(SB), NOSPLIT, $0-48\n", name)
	p("MOVD cvs+0(FP), R0")
	p("MOVD buf+8(FP), R1")
	p("MOVD key+16(FP), R2")
	p("MOVD ctr+24(FP), R3")
	p("MOVD flags+32(FP), R4")
	p("MOVD msg+40(FP), R10")
	for i := 0; i < 8; i++ {
		p("MOVWU %d(R2), R5", 4*i)
		p("VDUP R5, %s.S4", v(i))
	}
	for i, iv := range []uint32{0x6A09E667, 0xBB67AE85, 0x3C6EF372} {
		p("MOVD $0x%08X, R5", iv)
		p("VDUP R5, %s.S4", v(28+i))
	}
	p("MOVD $0xA54FF53A, R19")
	p("MOVD $0x0407060500030201, R5")
	p("MOVD $0x0C0F0E0D080B0A09, R7")
	p("VMOV R5, V31.D[0]")
	p("VMOV R7, V31.D[1]")
	p("MOVD R1, R11")
	p("ADD $%d, R1, R12", stride)
	p("ADD $%d, R1, R13", 2*stride)
	p("ADD $%d, R1, R14", 3*stride)
	p("MOVD $%d, R15", blocks)
	p("MOVD $64, R6")
	fmt.Fprintf(&b, "%s_loop:\n", name)
	// The block's message, transposed: msg[w] holds word w of each lane.
	for q := 0; q < 4; q++ {
		for j, r := range []string{"R11", "R12", "R13", "R14"} {
			p("VLD1.P 16(%s), [%s.S4]", r, v(16+j))
		}
		transpose4([4]int{16, 17, 18, 19}, [4]int{20, 21, 22, 23})
		for i := 0; i < 4; i++ {
			p("FMOVQ F%d, %d(R10)", 20+i, 16*(4*q+i))
		}
	}
	for i := 0; i < 3; i++ {
		p("VMOV %s.B16, %s.B16", v(28+i), v(8+i))
	}
	p("VDUP R19, V11.S4")
	p("FMOVQ (R3), F12")
	p("FMOVQ 16(R3), F13")
	p("VDUP R6, V14.S4")
	p("MOVWU.P 4(R4), R7")
	p("VDUP R7, V15.S4")
	perm := [16]int{2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8}
	var sched [16]int
	for i := range sched {
		sched[i] = i
	}
	for r := 0; r < 7; r++ {
		loadMsg(sched, 0)
		g4([4][4]int{{0, 4, 8, 12}, {1, 5, 9, 13}, {2, 6, 10, 14}, {3, 7, 11, 15}})
		loadMsg(sched, 8)
		g4([4][4]int{{0, 5, 10, 15}, {1, 6, 11, 12}, {2, 7, 8, 13}, {3, 4, 9, 14}})
		var next [16]int
		for i := range next {
			next[i] = sched[perm[i]]
		}
		sched = next
	}
	for i := 0; i < 8; i++ {
		p("VEOR %s.B16, %s.B16, %s.B16", v(8+i), v(i), v(i))
	}
	p("SUBS $1, R15, R15")
	p("BNE %s_loop", name)
	// cvs[j] = lane j of V0-V7.
	transpose4([4]int{0, 1, 2, 3}, [4]int{16, 17, 18, 19})
	transpose4([4]int{4, 5, 6, 7}, [4]int{20, 21, 22, 23})
	for j := 0; j < 4; j++ {
		p("FMOVQ F%d, %d(R0)", 16+j, 32*j)
		p("FMOVQ F%d, %d(R0)", 20+j, 32*j+16)
	}
	p("RET")
}
